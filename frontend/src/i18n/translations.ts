export function localizeRegionName(
  rawName: string | undefined,
  lat: number,
  lon: number,
  lang: AppLanguage
): string {
  if (rawName && (rawName.startsWith('Drawn Field (') || rawName.startsWith('Feld-Auswahl ('))) {
    const areaPart = rawName.slice(rawName.indexOf('('));
    return lang === 'de' ? `Feld-Auswahl ${areaPart}` : `Drawn Field ${areaPart}`;
  }
  const matchedPreset = PRESET_REGIONS.find(
    (p) => Math.abs(p.lat - lat) < 0.05 && Math.abs(p.lon - lon) < 0.05
  );
  if (matchedPreset) {
    return PRESET_TEXT[lang][matchedPreset.id]?.name ?? matchedPreset.name;
  }
  if (!rawName || rawName.startsWith('Custom Site (') || rawName.startsWith('Eigener Standort (')) {
    const latHem = lat >= 0 ? 'N' : 'S';
    const lonHem = lon >= 0 ? 'E' : 'W';
    const prefix = lang === 'de' ? 'Standort' : 'Site';
    return `${prefix} (${Math.abs(lat).toFixed(3)}°${latHem}, ${Math.abs(lon).toFixed(3)}°${lonHem})`;
  }
  return rawName;
}

